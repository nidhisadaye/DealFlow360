USE dealflow360;

CREATE TABLE customers (
  id VARCHAR(20) PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  company VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL,
  phone VARCHAR(20),
  tier ENUM('BRONZE', 'SILVER', 'GOLD') NOT NULL,
  credit_limit DECIMAL(12,2),
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE products (
  id VARCHAR(20) PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  description TEXT,
  category VARCHAR(100) NOT NULL,
  type ENUM('GOOD', 'SERVICE') NOT NULL,
  billing_type ENUM('ONE_TIME', 'RECURRING') NOT NULL,
  sale_price DECIMAL(12,2) NOT NULL,
  cost_price DECIMAL(12,2) NOT NULL,
  currency VARCHAR(10) DEFAULT 'INR',
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE warehouses (
  id VARCHAR(20) PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  location VARCHAR(255) NOT NULL,
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE inventory (
  id VARCHAR(20) PRIMARY KEY,
  warehouse_id VARCHAR(20) NOT NULL,
  product_id VARCHAR(20) NOT NULL,
  available_quantity INT DEFAULT 0,
  reserved_quantity INT DEFAULT 0,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (warehouse_id) REFERENCES warehouses(id),
  FOREIGN KEY (product_id) REFERENCES products(id)
);

CREATE TABLE users (
  id VARCHAR(20) PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('SALES_REP', 'SALES_MANAGER', 'FINANCE_OPERATIONS', 'CUSTOMER', 'ADMIN') NOT NULL,
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS deals (
  id VARCHAR(20) PRIMARY KEY,
  customer_id VARCHAR(20) NOT NULL,
  sales_rep_id VARCHAR(20) NOT NULL,
  title VARCHAR(255) NOT NULL,
  status ENUM('DRAFT','UNDER_REVIEW','APPROVAL_REQUIRED','APPROVED','REJECTED','NEGOTIATION','REAPPROVAL_REQUIRED','FULFILLMENT_PENDING','READY_TO_BILL','CLOSED') NOT NULL DEFAULT 'DRAFT',
  discount_percent DECIMAL(5,2) DEFAULT 0,
  subtotal DECIMAL(12,2) DEFAULT 0,
  discount_amount DECIMAL(12,2) DEFAULT 0,
  total_amount DECIMAL(12,2) DEFAULT 0,
  cost_amount DECIMAL(12,2) DEFAULT 0,
  margin_amount DECIMAL(12,2) DEFAULT 0,
  margin_percent DECIMAL(5,2) DEFAULT 0,
  risk_score INT DEFAULT 0,
  risk_level ENUM('LOW','MEDIUM','HIGH','CRITICAL') DEFAULT 'LOW',
  currency VARCHAR(10) DEFAULT 'INR',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (customer_id) REFERENCES customers(id),
  FOREIGN KEY (sales_rep_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS deal_items (
  id VARCHAR(20) PRIMARY KEY,
  deal_id VARCHAR(20) NOT NULL,
  product_id VARCHAR(20) NOT NULL,
  product_name VARCHAR(255) NOT NULL,
  quantity INT NOT NULL,
  unit_price DECIMAL(12,2) NOT NULL,
  unit_cost DECIMAL(12,2) NOT NULL,
  billing_type ENUM('ONE_TIME','RECURRING') NOT NULL,
  recurring_interval ENUM('MONTHLY','QUARTERLY','YEARLY') NULL,
  discount_percent DECIMAL(5,2) DEFAULT 0,
  subtotal DECIMAL(12,2) NOT NULL,
  total DECIMAL(12,2) NOT NULL,
  FOREIGN KEY (deal_id) REFERENCES deals(id) ON DELETE CASCADE,
  FOREIGN KEY (product_id) REFERENCES products(id)
);

CREATE TABLE IF NOT EXISTS approval_requests (
  id VARCHAR(20) PRIMARY KEY,
  deal_id VARCHAR(20) NOT NULL,
  requested_by VARCHAR(20) NOT NULL,
  approver_role ENUM('SALES_REP','SALES_MANAGER','FINANCE_OPERATIONS','CUSTOMER','ADMIN') NOT NULL,
  status ENUM('PENDING','APPROVED','REJECTED') NOT NULL DEFAULT 'PENDING',
  reason VARCHAR(500),
  requested_discount_percent DECIMAL(5,2),
  allowed_discount_percent DECIMAL(5,2),
  risk_score INT,
  comments VARCHAR(500),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (deal_id) REFERENCES deals(id) ON DELETE CASCADE,
  FOREIGN KEY (requested_by) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS deal_events (
  id VARCHAR(20) PRIMARY KEY,
  deal_id VARCHAR(20) NOT NULL,
  event_type ENUM('DEAL_CREATED','DEAL_UPDATED','DISCOUNT_CHANGED','EVALUATION_COMPLETED','APPROVAL_REQUESTED','APPROVED','REJECTED','UPSELL_ADDED','WAREHOUSE_ALLOCATED','NEGOTIATION_STARTED','NEGOTIATION_REQUESTED','REAPPROVAL_TRIGGERED','BILLING_CREATED','STATUS_CHANGED') NOT NULL,
  actor_id VARCHAR(20) NOT NULL,
  description VARCHAR(500) NOT NULL,
  metadata JSON,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (deal_id) REFERENCES deals(id) ON DELETE CASCADE,
  FOREIGN KEY (actor_id) REFERENCES users(id)
);